// Generates migrations/0025_overeenkomst_templates_seed.sql from content/legal/*.md.
// Run: node scripts/portal-seed-templates.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CREATED_AT = 1760000000000;
const TEMPLATES = [
  { id: 'tpl_overeenkomst_1_0', slug: 'overeenkomst', title: 'Overeenkomst van opdracht', file: 'overeenkomst.md' },
  { id: 'tpl_av_1_0', slug: 'algemene-voorwaarden', title: 'Algemene Voorwaarden AanloopAI', file: 'algemene-voorwaarden.md' },
  { id: 'tpl_privacy_1_0', slug: 'privacy-verwerker', title: 'Privacyverklaring en Verwerkersovereenkomst', file: 'privacy-verwerker.md' },
];

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const out = [
  '-- 0025: seed agr_templates v1.0 from content/legal/*.md (generated by scripts/portal-seed-templates.mjs).',
  '-- Apply with: wrangler d1 execute aanloop-portal --remote --file=migrations/0025_overeenkomst_templates_seed.sql',
];
for (const t of TEMPLATES) {
  const body = readFileSync(join(root, 'content', 'legal', t.file), 'utf8').replace(/\r\n/g, '\n');
  out.push(
    `INSERT OR IGNORE INTO agr_templates (id, slug, version, title, body_markdown, effective_from, created_at) VALUES (${q(t.id)}, ${q(t.slug)}, '1.0', ${q(t.title)}, ${q(body)}, ${CREATED_AT}, ${CREATED_AT});`,
  );
}
writeFileSync(join(root, 'migrations', '0025_overeenkomst_templates_seed.sql'), `${out.join('\n')}\n`, 'utf8');
console.log('wrote migrations/0025_overeenkomst_templates_seed.sql');
